package http

import (
	"fmt"
	"io"
	"net/http"
	"news-aggregator/internal/cache"
	"news-aggregator/internal/models"
	"news-aggregator/internal/service"
	"strings"
	"time"

	"github.com/gin-gonic/gin"
	"gorm.io/gorm"
)

type NewsHandler struct {
	service  service.NewsService
	db       *gorm.DB
	cacheSvc cache.CacheService
}

func NewNewsHandler(s service.NewsService, dbs ...*gorm.DB) *NewsHandler {
	var db *gorm.DB
	if len(dbs) > 0 {
		db = dbs[0]
	}
	return &NewsHandler{service: s, db: db}
}

func (h *NewsHandler) WithCache(c cache.CacheService) *NewsHandler {
	h.cacheSvc = c
	return h
}

// Health godoc
// @Summary      Health and system readiness check
// @Description  Returns the operational status of the service, database connectivity, and timestamp.
// @Tags         System
// @Produce      json
// @Success      200 {object} map[string]interface{} "Service is healthy and operational"
// @Failure      503 {object} map[string]interface{} "Database connectivity failure"
// @Router       /api/v1/health [get]
func (h *NewsHandler) Health(c *gin.Context) {
	dbStatus := "connected"
	if h.db != nil {
		sqlDB, err := h.db.DB()
		if err != nil || sqlDB.Ping() != nil {
			dbStatus = "disconnected"
			c.JSON(http.StatusServiceUnavailable, gin.H{
				"status":   "degraded",
				"database": dbStatus,
			})
			return
		}
	}

	redisStatus := "disabled"
	if h.cacheSvc != nil && h.cacheSvc.IsAvailable() {
		redisStatus = "connected"
	}

	c.JSON(http.StatusOK, gin.H{
		"status":   "ok",
		"database": dbStatus,
		"redis":    redisStatus,
		"time":     time.Now().UTC().Format(time.RFC3339),
	})
}

// Summarize godoc
// @Summary      Summarize news articles concurrently
// @Description  Scrapes provided news URLs in parallel using goroutines, extracts content & real titles, queries configured AI provider with fallback, and caches results.
// @Tags         News
// @Accept       json
// @Produce      json
// @Security     ApiKeyAuth
// @Param        request body models.SummarizeRequest true "List of news URLs to summarize"
// @Success      200 {array} models.ArticleResponse "List of summarized articles"
// @Failure      400 {object} map[string]string "Invalid request or validation error"
// @Failure      401 {object} map[string]string "API Key missing or invalid"
// @Failure      403 {object} map[string]string "Quota exceeded"
// @Failure      500 {object} map[string]string "Internal processing error"
// @Router       /api/v1/summarize [post]
func (h *NewsHandler) Summarize(c *gin.Context) {
	var req models.SummarizeRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid request body: urls must be a non-empty list of valid URLs"})
		return
	}

	apiKey := c.GetHeader("X-API-KEY")
	res, err := h.service.SummarizeArticles(c.Request.Context(), apiKey, req.URLs)
	if err != nil {
		if strings.Contains(err.Error(), "validation failed") || strings.Contains(err.Error(), "no valid") {
			c.JSON(http.StatusBadRequest, gin.H{"error": err.Error()})
			return
		}
		if strings.Contains(err.Error(), "quota exceeded") {
			c.JSON(http.StatusForbidden, gin.H{"error": err.Error()})
			return
		}
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}

	c.JSON(http.StatusOK, res)
}

